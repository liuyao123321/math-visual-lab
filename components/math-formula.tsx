"use client";

import { useMemo } from "react";
import { renderFormula, splitMathText } from "@/lib/formula";

export function MathFormula({ value, block = true }: { value: string; block?: boolean }) {
  const parts = splitMathText(value, false);
  const mixed = parts.some((part) => part.kind === "math") && (parts.length > 1);
  const rendered = useMemo(() => {
    try { return renderFormula(value, block); } catch { return null; }
  }, [value, block]);
  const fallback = (
    <code
      className="inline-block whitespace-pre-wrap rounded-md bg-amber-500/15 px-2 py-1 text-sm text-amber-900 dark:text-amber-200"
      data-formula-error="true"
      title="公式格式无法排版，已保留原文，请核对"
    >
      {value}
    </code>
  );
  return <span className={block ? "math-formula math-formula--block block max-w-full min-w-0 overflow-x-auto rounded-lg bg-muted px-4 py-3 text-foreground ring-1 ring-border" : "math-formula math-formula--inline"}>
    {rendered ? <span dangerouslySetInnerHTML={{ __html: rendered }} /> : mixed ? <MathText value={value} /> : fallback}
  </span>;
}

/** Only HTML generated by untrusted-input KaTeX is inserted; prose is never HTML. */
export function MathText({ value }: { value: string }) {
  return <span className="math-text whitespace-pre-wrap">{splitMathText(value).map((part, index) => part.kind === "math"
    ? <MathFormula key={index} value={part.value} block={part.display} />
    : <span key={index}>{part.value}</span>)}</span>;
}
